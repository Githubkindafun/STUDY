// korzystamy tutaj z takiego polaczenia sin + gamma bo
// sin bedzie tym plynnym oddychaniem a gamma pozwoli odpowiednio dobrac 
// odpowiednia wartosc PWM
void sinRgb(uint8_t r, uint8_t g, uint8_t b, uint8_t sin) {
    uint16_t rSin = ((uint16_t)r * sin) / 255;
    uint16_t gSin = ((uint16_t)g * sin) / 255;
    uint16_t bSin = ((uint16_t)b * sin) / 255;
    OCR1B = 255 - pgm_read_byte(&gamma8[(uint8_t)rSin]);
    OCR1A = 255 - pgm_read_byte(&gamma8[(uint8_t)gSin]);
    OCR2A = 255 - pgm_read_byte(&gamma8[(uint8_t)bSin]);
}

int main() {
    timer1_init();
    timer2_init();
    srand(420);

    uint16_t hue = rand() % 360;
    uint8_t r = pgm_read_byte(&hsvToRgb[hue].r);
    uint8_t g = pgm_read_byte(&hsvToRgb[hue].g);
    uint8_t b = pgm_read_byte(&hsvToRgb[hue].b);
    uint8_t flag = 0;

    while(1) {
        uint8_t sinVal = pgm_read_byte(&sin8Wave[flag]);
        sinRgb(r, g, b, sinVal);
        _delay_ms(DELAY);
        flag++;
        if(flag == 255) {
            hue = rand() % 360; 
            r = pgm_read_byte(&hsvToRgb[hue].r);
            g = pgm_read_byte(&hsvToRgb[hue].g);
            b = pgm_read_byte(&hsvToRgb[hue].b);
            flag = 0;
        }
    }
}