void timer1_init()
{
  // ustaw tryb licznika
  // CS1   = 001  -- prescaler 1
  TCCR1B |= _BV(CS10);
  // ustawiamy na "Clear on Compare Match", set at BOTTOM (non-inverting)
  // oczywiscie jest to A bo PB1 jest OC1A
  TCCR1A |= _BV(COM1A1);
  TCCR1A |= _BV(COM1B1); // oba na non-inverting
  // ustawiamy TOP na 255
  ICR1 = 255;
  // ustawiamy fast PWM z TOP jako ICR1
  TCCR1A |= _BV(WGM11);
  TCCR1B |= _BV(WGM12) | _BV(WGM13);
  // no i jest LEDik
  DDRB |= _BV(BLUE) | _BV(RED);
}

void timer2_init() {
    // fast PWM z top na 255
    TCCR2A |= _BV(WGM20) | _BV(WGM21);
    // non-inverting
    TCCR2A |= _BV(COM2A1);
    // prescaler na 1
    TCCR2B |= _BV(CS20);
    DDRB |= _BV(GREEN);
}

